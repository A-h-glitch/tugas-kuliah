private void loadBook(String filePath) {
    try {
        // baca isi file
        String content = java.nio.file.Files.readString(
                java.nio.file.Path.of(filePath)
        );

        // tampilkan ke jTextArea1
        jTextArea1.setText(content);
        jTextArea1.setCaretPosition(0); // mulai dari atas

    } catch (Exception e) {
        e.printStackTrace();
        jTextArea1.setText("Gagal membaca file:\n" + e.getMessage());
    }
}



