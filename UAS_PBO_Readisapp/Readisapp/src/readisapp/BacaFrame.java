public BacaFrame(String filePath) {
    initComponents();


    try {
        // baca isi file
        String content = java.nio.file.Files.readString(java.nio.file.Path.of(filePath));

        // tampilkan ke panel (ubah jPanel1 menjadi text area)
        javax.swing.JTextArea area = new javax.swing.JTextArea(content);
        area.setEditable(false);
        area.setLineWrap(true);
        area.setWrapStyleWord(true);

        javax.swing.JScrollPane scroll = new javax.swing.JScrollPane(area);

        jPanel1.setLayout(new java.awt.BorderLayout());
        jPanel1.add(scroll, java.awt.BorderLayout.CENTER);

    } catch (Exception e) {
        e.printStackTrace();
    }
}

